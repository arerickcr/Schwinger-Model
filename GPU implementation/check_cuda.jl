include("SchwingerGPU.jl")
include("CUDABackend.jl")
using .SchwingerGPU, .CUDABackend, CUDA, ITensors, ITensorMPS
using Test
CUDA.versioninfo()
backend = cuda_backend()
p = Model(N=4)
c = Solver(nsweeps=12,maxdim=16,noise=1e-12,eig_maxiter=5,outputlevel=0)
prob = build_problem(p)
H = backend.upload(prob.H)
psi0 = backend.upload(prob.psi0)
@test all(eltype(t) == Float64 for t in H)
@test all(ITensors.NDTensors.iscu(ITensors.tensor(t)) for t in H)
@test all(eltype(t) == Float64 for t in psi0)
@test all(ITensors.NDTensors.iscu(ITensors.tensor(t)) for t in psi0)
report = compare_case(p,c,backend;directory=joinpath(@__DIR__,"results"),label="cuda_smoke_N4")
@test all(row["energy_agrees"] for row in report["states"])
@test all(row["fidelity"] > 1-1e-7 for row in report["states"])
println("CUDA smoke check passed. This is not the N=10:20 study.")
